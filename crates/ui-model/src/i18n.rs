#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Lang {
    Ru,
    En,
}

impl Lang {
    pub fn from_system(locale: Option<&str>) -> Self {
        match locale {
            Some(locale) if locale.to_lowercase().starts_with("ru") => Self::Ru,
            _ => Self::En,
        }
    }

    pub fn from_preference(preference: Option<&str>, system: Option<&str>) -> Self {
        match preference {
            Some("auto") | None => Self::from_system(system),
            Some(locale) => Self::from_system(Some(locale)),
        }
    }

    pub fn code(self) -> &'static str {
        match self {
            Self::Ru => "ru",
            Self::En => "en",
        }
    }
}

